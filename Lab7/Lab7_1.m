n = inputdlg({'x =', 'Кількість повторів N=', 'Відповідь:'}, 'Варіант 16', 1);
x = str2double(n(1));
N = str2double(n(2));

% Початкове значення першого доданка (1/x) та суми
n = 1 / x;
S = n;

for k = 1:N
  n = n / (x + k); % Рекурентне обчислення наступного доданка
  S = S + n; % Додавання до загальної суми
end

x_str = num2str(x);
N_str = num2str(N);
S_str = num2str(S);
n = inputdlg({'x =', 'Кількість повторів N=', 'Відповідь:'}, ...
              'Варіант 16', 1, {x_str, N_str, S_str});